create or replace function public.create_product_from_delivery_item(
  p_delivery_item_id uuid,
  p_product jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item public.supplier_delivery_items%rowtype;
  v_delivery public.supplier_deliveries%rowtype;
  v_brand_id uuid;
  v_product_id uuid;
  v_category_id uuid;
  v_sale_price bigint;
  v_old_price bigint;
  v_minimum_stock integer;
  v_warranty integer;
  v_commission_type text;
  v_commission_value bigint;
  v_sku text;
  v_slug text;
begin
  if not public.is_admin() then raise exception 'Только управляющий может добавлять товары'; end if;
  if jsonb_typeof(p_product) <> 'object' then raise exception 'Некорректные данные товара'; end if;

  select * into v_item from public.supplier_delivery_items
  where id = p_delivery_item_id for update;
  if not found then raise exception 'Строка поставки не найдена'; end if;
  if v_item.product_id is not null then raise exception 'Для этой модели товар уже создан'; end if;

  select * into v_delivery from public.supplier_deliveries
  where id = v_item.delivery_id and status = 'received' for update;
  if not found then raise exception 'Поставка недоступна'; end if;

  begin
    v_category_id := (p_product ->> 'category_id')::uuid;
    v_sale_price := (p_product ->> 'sale_price_tyiyn')::bigint;
    v_old_price := nullif(p_product ->> 'old_price_tyiyn','')::bigint;
    v_minimum_stock := coalesce((p_product ->> 'minimum_stock')::integer,0);
    v_warranty := coalesce((p_product ->> 'warranty_months')::integer,0);
    v_commission_value := (p_product ->> 'manager_commission_value')::bigint;
  exception when others then
    raise exception 'Проверьте категорию, цену, остаток, гарантию и комиссию';
  end;

  v_commission_type := coalesce(p_product ->> 'manager_commission_type','percent');
  v_sku := trim(coalesce(p_product ->> 'sku',''));
  v_slug := trim(coalesce(p_product ->> 'slug',''));

  if not exists (select 1 from public.categories where id = v_category_id and is_active) then
    raise exception 'Выберите действующую категорию';
  end if;
  if length(trim(coalesce(p_product ->> 'name_ru',''))) < 2 then raise exception 'Укажите название товара'; end if;
  if length(v_sku) < 2 or length(v_slug) < 2 then raise exception 'Укажите SKU и адрес товара'; end if;
  if v_sale_price <= 0 then raise exception 'Цена продажи должна быть больше нуля'; end if;
  if v_old_price is not null and v_old_price < v_sale_price then raise exception 'Старая цена не может быть ниже цены продажи'; end if;
  if v_minimum_stock < 0 or v_warranty < 0 then raise exception 'Остаток и гарантия не могут быть отрицательными'; end if;
  if v_commission_type not in ('percent','fixed') then raise exception 'Некорректный тип комиссии'; end if;
  if v_commission_value < 0 then raise exception 'Комиссия не может быть отрицательной'; end if;
  if v_commission_type = 'percent' and v_commission_value > 10000 then
    raise exception 'Процент менеджера не может превышать 100%%';
  end if;

  select id into v_brand_id from public.brands
  where lower(name) = lower(v_item.brand)
  order by created_at limit 1;
  if v_brand_id is null then
    insert into public.brands(name, slug)
    values (
      v_item.brand,
      left(regexp_replace(lower(v_item.brand), '[^a-z0-9а-яё]+', '-', 'gi'), 80)
        || '-' || substr(replace(gen_random_uuid()::text,'-',''),1,8)
    ) returning id into v_brand_id;
  end if;

  insert into public.products (
    category_id, brand_id, sku, slug, model,
    name_ru, name_kg, name_en,
    description_ru, description_kg, description_en,
    specifications, sale_price_tyiyn, old_price_tyiyn,
    stock_quantity, reserved_quantity, minimum_stock, warranty_months,
    installment_allowed, manager_commission_type, manager_commission_value,
    is_active, is_featured, status, created_by
  ) values (
    v_category_id, v_brand_id, v_sku, v_slug, v_item.model,
    trim(p_product ->> 'name_ru'),
    coalesce(nullif(trim(p_product ->> 'name_kg'),''), trim(p_product ->> 'name_ru')),
    coalesce(nullif(trim(p_product ->> 'name_en'),''), trim(p_product ->> 'name_ru')),
    nullif(trim(p_product ->> 'description_ru'),''),
    nullif(trim(p_product ->> 'description_kg'),''),
    nullif(trim(p_product ->> 'description_en'),''),
    coalesce(p_product -> 'specifications','[]'::jsonb),
    v_sale_price, v_old_price,
    0, 0, v_minimum_stock, v_warranty,
    coalesce((p_product ->> 'installment_allowed')::boolean,true),
    v_commission_type, v_commission_value,
    coalesce((p_product ->> 'is_active')::boolean,true),
    coalesce((p_product ->> 'is_featured')::boolean,false),
    case when coalesce((p_product ->> 'is_active')::boolean,true) then 'out_of_stock' else 'hidden' end,
    auth.uid()
  ) returning id into v_product_id;

  insert into public.supplier_products (
    supplier_id, product_id, supplier_sku, purchase_price_tyiyn,
    is_primary, is_active, last_purchase_at, delivery_item_id
  ) values (
    v_delivery.supplier_id, v_product_id, v_item.supplier_sku,
    v_item.purchase_price_tyiyn, true, true, v_delivery.delivered_at, v_item.id
  );

  update public.supplier_delivery_items
  set product_id = v_product_id, updated_at = now()
  where id = v_item.id;

  insert into public.inventory_movements (
    product_id, movement_type, quantity_delta, balance_after,
    reference_type, reference_id, supplier_id, note, created_by
  ) values (
    v_product_id, 'purchase', v_item.quantity, 0,
    'supplier_delivery_item', v_item.id, v_delivery.supplier_id,
    'Приход по поставке №' || v_delivery.delivery_number::text,
    auth.uid()
  );

  return jsonb_build_object(
    'product_id', v_product_id,
    'delivery_item_id', v_item.id,
    'supplier_id', v_delivery.supplier_id,
    'stock_quantity', v_item.quantity,
    'purchase_price_tyiyn', v_item.purchase_price_tyiyn
  );
end;
$$;

create or replace function public.delete_product_safely(p_product_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Только управляющий может удалять товары'; end if;
