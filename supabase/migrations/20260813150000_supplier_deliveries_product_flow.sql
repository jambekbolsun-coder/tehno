  if p_purchase_method = 'installment' and p_installment_months is null then raise exception 'Укажите срок рассрочки'; end if;
  if p_purchase_method = 'full' then p_installment_months := null; end if;

  v_result := public.create_staff_order(
    p_customer,
    p_items,
    p_sale_channel,
    p_source,
    p_delivery,
    p_comment,
    p_assigned_manager_id
  );

  update public.orders
  set requested_purchase_method = p_purchase_method,
      requested_installment_months = p_installment_months
  where id = (v_result ->> 'order_id')::uuid
  returning * into v_order;

  return v_result || jsonb_build_object(
    'total_tyiyn', v_order.total_tyiyn,
    'subtotal_tyiyn', v_order.subtotal_tyiyn,
    'requested_purchase_method', v_order.requested_purchase_method,
    'requested_installment_months', v_order.requested_installment_months
  );
end;
$$;

