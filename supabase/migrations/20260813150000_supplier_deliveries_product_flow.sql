  values (
    auth.uid(), 'products', p_product_id::text, 'RPC',
    jsonb_build_object('function','delete_product_safely','operation','soft_delete')
  );
end;
$$;

create or replace function public.calculate_installment_terms(
  p_amount_tyiyn bigint,
  p_months integer
)
returns jsonb
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_config jsonb;
  v_plan jsonb;
  v_rate integer;
  v_minimum bigint;
  v_overpayment bigint;
  v_total bigint;
begin
  if p_amount_tyiyn <= 0 then raise exception 'Сумма рассрочки должна быть больше нуля'; end if;
  if p_months is null or p_months < 1 or p_months > 12 then raise exception 'Некорректный срок рассрочки'; end if;

  select value into v_config from public.app_settings where key = 'installment_config';
  v_config := coalesce(v_config, '{}'::jsonb);
  v_minimum := coalesce((v_config ->> 'minimum_tyiyn')::bigint,0);
  if p_amount_tyiyn < v_minimum then raise exception 'Сумма меньше минимальной для рассрочки'; end if;

  select value into v_plan
  from jsonb_array_elements(coalesce(v_config -> 'plans','[]'::jsonb))
  where coalesce((value ->> 'enabled')::boolean,false)
    and (value ->> 'months')::integer = p_months
  limit 1;
  if v_plan is null then raise exception 'Выбранный срок рассрочки недоступен'; end if;

  v_rate := coalesce((v_plan ->> 'rate_basis_points')::integer,0);
  v_overpayment := round(p_amount_tyiyn::numeric * v_rate / 10000)::bigint;
  v_total := p_amount_tyiyn + v_overpayment;

  return jsonb_build_object(
    'months', p_months,
    'rate_basis_points', v_rate,
    'base_tyiyn', p_amount_tyiyn,
    'overpayment_tyiyn', v_overpayment,
    'total_tyiyn', v_total,
    'monthly_payment_tyiyn', (v_total + p_months - 1) / p_months
  );
end;
$$;

create or replace function public.apply_installment_terms_to_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_base bigint;
  v_terms jsonb;
begin
  if new.requested_purchase_method = 'installment' then
    if new.requested_installment_months is null then raise exception 'Укажите срок рассрочки'; end if;
    v_base := coalesce(
      nullif(new.request_metadata ->> 'installment_base_tyiyn','')::bigint,
      new.subtotal_tyiyn - new.discount_tyiyn + new.delivery_tyiyn
    );
    v_terms := public.calculate_installment_terms(v_base, new.requested_installment_months);
    new.total_tyiyn := (v_terms ->> 'total_tyiyn')::bigint;
    new.request_metadata := coalesce(new.request_metadata,'{}'::jsonb) || jsonb_build_object(
      'installment_rate_applied', true,
      'installment_base_tyiyn', v_base,
      'installment_rate_basis_points', (v_terms ->> 'rate_basis_points')::integer,
      'installment_overpayment_tyiyn', (v_terms ->> 'overpayment_tyiyn')::bigint,
      'installment_monthly_payment_tyiyn', (v_terms ->> 'monthly_payment_tyiyn')::bigint
    );
  elsif coalesce((new.request_metadata ->> 'installment_rate_applied')::boolean,false) then
    v_base := coalesce(
      nullif(new.request_metadata ->> 'installment_base_tyiyn','')::bigint,
      new.subtotal_tyiyn - new.discount_tyiyn + new.delivery_tyiyn
    );
    new.total_tyiyn := v_base;
    new.request_metadata := new.request_metadata
      - 'installment_rate_applied'
      - 'installment_rate_basis_points'
      - 'installment_overpayment_tyiyn'
      - 'installment_monthly_payment_tyiyn';
  end if;
  return new;
end;
$$;

drop trigger if exists orders_apply_installment_terms on public.orders;
create trigger orders_apply_installment_terms
before insert or update of requested_purchase_method, requested_installment_months, subtotal_tyiyn, discount_tyiyn, delivery_tyiyn
on public.orders
for each row execute function public.apply_installment_terms_to_order();

