create or replace function public.create_staff_order_with_payment(
  p_customer jsonb,
  p_items jsonb,
  p_sale_channel text default 'offline',
  p_source text default 'store',
  p_delivery jsonb default '{}'::jsonb,
  p_comment text default null,
