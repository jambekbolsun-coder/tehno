-- Supplier delivery -> product -> inventory -> finance flow.
-- Also makes installment totals and schedules use the same configured rates
-- as the storefront calculator.

create table if not exists public.supplier_deliveries (
  id uuid primary key default gen_random_uuid(),
  delivery_number bigint generated by default as identity unique,
  supplier_id uuid not null references public.suppliers(id) on delete restrict,
  delivered_at date not null default current_date,
  total_quantity integer not null check (total_quantity > 0),
  notes text,
  status text not null default 'received'
    check (status in ('received','cancelled')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.supplier_delivery_items (
  id uuid primary key default gen_random_uuid(),
  delivery_id uuid not null references public.supplier_deliveries(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null check (length(trim(product_name)) between 2 and 160),
  brand text not null check (length(trim(brand)) between 1 and 100),
  model text not null check (length(trim(model)) between 1 and 120),
  supplier_sku text,
  quantity integer not null check (quantity > 0),
  purchase_price_tyiyn bigint not null check (purchase_price_tyiyn > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (delivery_id, model, supplier_sku)
);

create index if not exists supplier_deliveries_supplier_id_idx
  on public.supplier_deliveries(supplier_id, delivered_at desc);
create index if not exists supplier_deliveries_created_by_idx
  on public.supplier_deliveries(created_by);
create index if not exists supplier_delivery_items_delivery_id_idx
  on public.supplier_delivery_items(delivery_id);
create index if not exists supplier_delivery_items_product_id_idx
  on public.supplier_delivery_items(product_id);

alter table public.products
  add column if not exists deleted_at timestamptz;

alter table public.supplier_products
  add column if not exists delivery_item_id uuid
    references public.supplier_delivery_items(id) on delete set null;
create unique index if not exists supplier_products_delivery_item_id_uidx
  on public.supplier_products(delivery_item_id)
  where delivery_item_id is not null;

alter table public.supplier_deliveries enable row level security;
alter table public.supplier_delivery_items enable row level security;

drop policy if exists supplier_deliveries_admin_all on public.supplier_deliveries;
create policy supplier_deliveries_admin_all
on public.supplier_deliveries for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

drop policy if exists supplier_delivery_items_admin_all on public.supplier_delivery_items;
create policy supplier_delivery_items_admin_all
on public.supplier_delivery_items for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

grant select, insert, update, delete on public.supplier_deliveries to authenticated;
grant select, insert, update, delete on public.supplier_delivery_items to authenticated;

create or replace function public.create_supplier_with_delivery(
  p_supplier jsonb,
  p_items jsonb,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_supplier_id uuid;
  v_delivery_id uuid;
  v_delivery_number bigint;
  v_item jsonb;
  v_quantity integer;
  v_purchase_price bigint;
  v_total_quantity integer := 0;
  v_name text;
begin
  if not public.is_admin() then raise exception 'Только управляющий может оформлять поставки'; end if;
  if jsonb_typeof(p_supplier) <> 'object' then raise exception 'Укажите поставщика'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Добавьте хотя бы одну модель поставки';
  end if;
  if jsonb_array_length(p_items) > 50 then raise exception 'В одной поставке допустимо не более 50 моделей'; end if;

  v_name := trim(coalesce(p_supplier ->> 'name',''));
  if length(v_name) < 2 then raise exception 'Укажите название поставщика'; end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    begin
      v_quantity := (v_item ->> 'quantity')::integer;
      v_purchase_price := (v_item ->> 'purchase_price_tyiyn')::bigint;
    exception when others then
      raise exception 'Проверьте количество и закупочную цену каждой модели';
    end;
    if length(trim(coalesce(v_item ->> 'product_name',''))) < 2
       or length(trim(coalesce(v_item ->> 'brand',''))) < 1
       or length(trim(coalesce(v_item ->> 'model',''))) < 1 then
      raise exception 'Укажите товар, бренд и модель в каждой строке';
    end if;
    if v_quantity <= 0 or v_quantity > 100000 then raise exception 'Количество каждой модели должно быть больше нуля'; end if;
    if v_purchase_price <= 0 then raise exception 'Закупочная цена должна быть больше нуля'; end if;
    v_total_quantity := v_total_quantity + v_quantity;
  end loop;

  insert into public.suppliers (
    name, contact_person, phone, whatsapp, email, address, notes, created_by
  ) values (
    v_name,
    nullif(trim(p_supplier ->> 'contact_person'),''),
    nullif(trim(p_supplier ->> 'phone'),''),
    nullif(trim(p_supplier ->> 'whatsapp'),''),
    nullif(trim(p_supplier ->> 'email'),''),
    nullif(trim(p_supplier ->> 'address'),''),
    nullif(trim(p_supplier ->> 'notes'),''),
    auth.uid()
  ) returning id into v_supplier_id;

  insert into public.supplier_deliveries (
    supplier_id, total_quantity, notes, created_by
  ) values (
    v_supplier_id, v_total_quantity, nullif(trim(p_notes),''), auth.uid()
  ) returning id, delivery_number into v_delivery_id, v_delivery_number;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    insert into public.supplier_delivery_items (
      delivery_id, product_name, brand, model, supplier_sku,
      quantity, purchase_price_tyiyn
    ) values (
      v_delivery_id,
      trim(v_item ->> 'product_name'),
      trim(v_item ->> 'brand'),
      trim(v_item ->> 'model'),
      nullif(trim(v_item ->> 'supplier_sku'),''),
      (v_item ->> 'quantity')::integer,
      (v_item ->> 'purchase_price_tyiyn')::bigint
    );
  end loop;

  return jsonb_build_object(
    'supplier_id', v_supplier_id,
    'delivery_id', v_delivery_id,
    'delivery_number', v_delivery_number,
    'total_quantity', v_total_quantity
  );
end;
$$;

